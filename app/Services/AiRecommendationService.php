<?php

namespace App\Services;

use App\Models\Assessment;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;

/**
 * Turns an assessment into plain-language findings ("what did we find?").
 * Uses Gemini when available; otherwise builds the same structure from the
 * SME's actual answers, so the result is always specific to them.
 */
class AiRecommendationService
{
    public function __construct(
        private ComplianceReportService $report,
        private MaturityScoringService $scoring,
    ) {
    }

    /**
     * Insights to display for an assessment in the current locale.
     *
     * @return array{overall:string, strengths:array, improvements:array, next_step:string, source:string}
     */
    public function insightsFor(Assessment $assessment): array
    {
        $locale = app()->getLocale();
        $stored = $assessment->ai_insights ?? [];
        $cached = $stored['summaries'][$locale] ?? null;

        if (is_array($cached) && ! empty($cached['overall'])) {
            return $cached;
        }

        $generated = $this->generateInsights($assessment);

        if ($generated) {
            $stored['summaries'][$locale] = $generated;
            $assessment->update(['ai_insights' => $stored]);

            return $generated;
        }

        return $this->ruleBasedInsights($assessment);
    }

    /**
     * Ask Gemini for structured insights. Returns null on any failure so the
     * caller can keep the rule-based version.
     */
    private function generateInsights(Assessment $assessment): ?array
    {
        $context = $this->promptContext($assessment);
        $language = $this->language();

        $prompt = <<<PROMPT
You are a friendly cybersecurity assistant explaining assessment results to a
non-technical small business owner in Malaysia. Write in {$language}.

{$context}

Return JSON with:
- "overall": 2-3 plain sentences on what the score means for this business.
- "strengths": up to 3 short phrases (2-5 words), taken ONLY from the practices listed as in place. Empty array if none.
- "improvements": up to 3 short phrases (2-5 words) naming the weak AREA, taken from the gap topics
  (the text before "priority"), most urgent first. Do not use the action titles here.
- "next_step": one sentence telling them to start with the first recommended action, quoting its exact title, and why.
Write numbers as digits (e.g. 65%). No jargon, no markdown, no product endorsements.
PROMPT;

        $json = $this->callGemini($prompt, 600, [
            'type' => 'OBJECT',
            'properties' => [
                'overall' => ['type' => 'STRING'],
                'strengths' => ['type' => 'ARRAY', 'items' => ['type' => 'STRING']],
                'improvements' => ['type' => 'ARRAY', 'items' => ['type' => 'STRING']],
                'next_step' => ['type' => 'STRING'],
            ],
            'required' => ['overall', 'strengths', 'improvements', 'next_step'],
        ]);

        $data = is_string($json) ? json_decode($json, true) : null;

        if (! is_array($data) || ! is_string($data['overall'] ?? null) || trim($data['overall']) === '') {
            return null;
        }

        $list = fn ($value) => collect(is_array($value) ? $value : [])
            ->filter(fn ($v) => is_string($v) && trim($v) !== '')
            ->map(fn ($v) => trim($v))
            ->take(3)
            ->values()
            ->all();

        $fallback = $this->ruleBasedInsights($assessment);

        return [
            'overall' => trim($data['overall']),
            'strengths' => $list($data['strengths'] ?? []),
            'improvements' => $list($data['improvements'] ?? []) ?: $fallback['improvements'],
            'next_step' => is_string($data['next_step'] ?? null) && trim($data['next_step']) !== ''
                ? trim($data['next_step'])
                : $fallback['next_step'],
            'source' => 'ai',
            'locale' => app()->getLocale(),
        ];
    }

    /**
     * A longer, plain-language explanation for "Explain my results".
     * Cached on the assessment per locale once generated by AI.
     *
     * @return array{text:string, source:string}
     */
    public function explain(Assessment $assessment): array
    {
        $locale = app()->getLocale();
        $insights = $assessment->ai_insights ?? [];
        $cached = $insights['explanations'][$locale] ?? null;

        if (is_string($cached) && $cached !== '') {
            return ['text' => $cached, 'source' => 'ai'];
        }

        $context = $this->promptContext($assessment);
        $language = $this->language();

        $prompt = <<<PROMPT
You are a friendly cybersecurity assistant. Explain these assessment results to a
non-technical small business owner in Malaysia, in {$language}.

{$context}

Write 5-7 short, warm, plain sentences as one paragraph: what the score means in
everyday terms, what they are already doing well, the biggest risk right now and
why it matters for a business like theirs, and which recommended action to start
with (use its exact title). Mention that each action has step-by-step guidance
in their Action Roadmap. Write numbers as digits (e.g. 65%). Do not open with a
greeting. No jargon, no markdown, no product endorsements. Output only the paragraph.
PROMPT;

        $text = $this->callGemini($prompt, 400);

        if (is_string($text) && trim($text) !== '') {
            $insights['explanations'][$locale] = trim($text);
            $assessment->update(['ai_insights' => $insights]);

            return ['text' => trim($text), 'source' => 'ai'];
        }

        return ['text' => $this->ruleBasedExplanation($assessment), 'source' => 'rules'];
    }

    public function ruleBasedInsights(Assessment $assessment): array
    {
        $assessment->loadMissing('user', 'domainScores.domain');
        $gaps = $this->report->prioritisedRecommendations($assessment);
        $strengths = $this->report->strengths($assessment);
        $weakestDomain = $assessment->domainScores->sortBy('score')->first();

        $overall = __(':business scored :score% overall, which places it at the :level maturity level (:risk).', [
            'business' => $assessment->user->business_name ?? $assessment->user->name,
            'score' => (float) $assessment->overall_score,
            'level' => __($assessment->overall_level),
            'risk' => __($this->scoring->riskLevelForPercentage((float) $assessment->overall_score)),
        ]).' '.$this->levelMeaning($assessment->overall_level);

        if ($gaps->isNotEmpty() && $weakestDomain) {
            $overall .= ' '.trans_choice(
                '{1} One area needs attention, and :domain is currently your weakest area.|[2,*] :count areas need attention, and :domain is currently your weakest area.',
                $gaps->count(),
                ['count' => $gaps->count(), 'domain' => $weakestDomain->domain->translatedName()]
            );
        }

        $first = $gaps->first();

        return [
            'overall' => $overall,
            'strengths' => $strengths->pluck('topic')->unique()->take(3)->values()->all(),
            'improvements' => $gaps->pluck('topic')->unique()->take(3)->values()->all(),
            'next_step' => $first
                ? __('Start with ":action". It is your highest-priority action and addresses :topic.', [
                    'action' => $first['action_title'],
                    'topic' => mb_strtolower($first['topic']),
                ])
                : __('Keep your current practices in place and retake the assessment in six months to stay on track.'),
            'source' => 'rules',
            'locale' => app()->getLocale(),
        ];
    }

    private function ruleBasedExplanation(Assessment $assessment): string
    {
        $insights = $this->ruleBasedInsights($assessment);
        $gaps = $this->report->prioritisedRecommendations($assessment);

        $parts = [$insights['overall']];

        if ($insights['strengths']) {
            $parts[] = __('You are already doing well in: :list.', ['list' => implode(', ', $insights['strengths'])]);
        }

        if ($gaps->isNotEmpty()) {
            $titles = $gaps->pluck('action_title')->take(2)->values();
            $parts[] = $titles->count() > 1
                ? __('I recommend starting with ":first", then ":second".', ['first' => $titles[0], 'second' => $titles[1]])
                : __('I recommend starting with ":first".', ['first' => $titles[0]]);
            $parts[] = __('Each action has simple step-by-step guidance in your Action Roadmap, so you can work through it at your own pace.');
        } else {
            $parts[] = $insights['next_step'];
        }

        return implode(' ', $parts);
    }

    private function levelMeaning(?string $level): string
    {
        return match ($level) {
            'Initial' => __('This means most basic protections are not yet in place, so the business is exposed to common attacks.'),
            'Developing' => __('This means some good habits exist, but important protections are still missing or inconsistent.'),
            'Managed' => __('This means your business has solid basic practices, with a few gaps left to close.'),
            default => __('This means strong, consistent practices are in place. Keep reviewing them regularly.'),
        };
    }

    private function promptContext(Assessment $assessment): string
    {
        $assessment->loadMissing('user', 'domainScores.domain');

        $business = $assessment->user->business_name ?? $assessment->user->name;
        $industry = $assessment->user->business_type ?? 'general';
        $risk = $this->scoring->riskLevelForPercentage((float) $assessment->overall_score);
        $score = (float) $assessment->overall_score;

        $domains = $assessment->domainScores->sortBy('domain.order')
            ->map(fn ($d) => "{$d->domain->translatedName()} {$d->score}%")
            ->implode(', ');

        $strengths = $this->report->strengths($assessment)->take(5)
            ->map(fn ($s) => "- {$s['topic']}")->implode("\n") ?: '- (none)';

        $gaps = $this->report->prioritisedRecommendations($assessment)->take(5)
            ->map(fn ($g) => "- {$g['topic']} (priority: {$g['priority']}); recommended action: \"{$g['action_title']}\"")
            ->implode("\n") ?: '- (none)';

        return <<<CTX
Business: "{$business}" (industry: {$industry}).
Overall score: {$score}% ({$assessment->overall_level}, {$risk}).
Domain scores: {$domains}.
Practices already in place:
{$strengths}
Gaps found, most urgent first:
{$gaps}
CTX;
    }

    private function language(): string
    {
        if (app()->getLocale() !== 'ms') {
            return 'English';
        }

        return <<<'STYLE'
natural Malaysian Bahasa Melayu, the way a Malaysian cybersecurity adviser would
talk to a small business owner. Rules:
- Address the owner as "anda". Clear, friendly and professional; not slang, not
  Indonesian, not textbook or government-letter Malay, not a word-for-word
  translation from English.
- Use short, plain sentences and everyday Malaysian terms: kata laluan, sandaran,
  pancingan data (phishing), kemas kini, insiden, PKS, pelanggan, akaun perniagaan.
- Avoid stiff phrases such as "Berdasarkan penilaian yang telah dijalankan, didapati
  bahawa", "Adalah dimaklumkan", "Sehubungan dengan itu", "Bagi tujuan",
  "Pengguna hendaklah", "Anda dikehendaki".
- Good example of tone: "Daripada penilaian anda, asas keselamatan siber perniagaan
  anda sudah ada. Cuma ada beberapa perkara yang masih perlu diberi perhatian,
  terutamanya dari segi kata laluan dan pelan tindakan apabila berlaku insiden."
- Keep action titles exactly as given (they are already in Bahasa Melayu) and always
  put them in double quotes, e.g. mulakan dengan "Semak Aktiviti Akaun Setiap Minggu".
- Only mention facts given above; do not guess the type of business or its products.
STYLE;
    }

    private function callGemini(string $prompt, int $maxTokens, ?array $schema = null): ?string
    {
        $apiKey = config('ai.gemini_api_key');

        if (! $apiKey) {
            return null;
        }

        $generationConfig = ['maxOutputTokens' => $maxTokens, 'temperature' => 0.4];

        if ($schema) {
            $generationConfig['responseMimeType'] = 'application/json';
            $generationConfig['responseSchema'] = $schema;
        }

        try {
            $response = Http::timeout(15)->post(
                'https://generativelanguage.googleapis.com/v1beta/models/'
                    .config('ai.gemini_model').':generateContent?key='.$apiKey,
                [
                    'contents' => [['role' => 'user', 'parts' => [['text' => $prompt]]]],
                    'generationConfig' => $generationConfig,
                ]
            );

            if (! $response->successful()) {
                Log::warning('Gemini request failed', ['status' => $response->status(), 'body' => $response->body()]);

                return null;
            }

            $text = $response->json('candidates.0.content.parts.0.text');

            return is_string($text) ? trim($text) : null;
        } catch (\Throwable $e) {
            Log::warning('Gemini request errored', ['message' => $e->getMessage()]);

            return null;
        }
    }
}
